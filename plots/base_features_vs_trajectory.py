#!/usr/bin/env python3
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.linear_model import LinearRegression
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

from hk_utils import REPO


IN_DIR_PRED = REPO / "plots" / "base_feature_prediction"
IN_DIR_TRAJ = REPO / "plots" / "ckpt_layer_trajectory_metrics"
OUT_DIR = REPO / "plots" / "base_features_vs_trajectory"
OUT_DIR.mkdir(parents=True, exist_ok=True)

FEATURES = [
    "min_pairwise_sigmoid_margin",
    "max_distractor_confidence",
    "correct_option_confidence",
    "earliest_layer_kint1",
    "mean_kint_layers",
    "std_kint_layers",
    "min_probe_probability_margin",
    "rank_alignment",
]


def main():
    # Requires outputs from previous scripts
    coef_path = IN_DIR_PRED / "feature_coefficients.csv"
    by_q_path = IN_DIR_TRAJ / "trajectory_metrics_by_method_subset.csv"
    if not coef_path.exists() or not by_q_path.exists():
        raise FileNotFoundError("Run predict_subset_from_base_features.py and quantify_ckpt_layer_trajectories.py first.")

    # Reconstruct per-question features by pulling from existing feature script output source if available
    # Here we read from the pooled file generated by predict script internals if user exports; fallback empty.
    feat_path = IN_DIR_PRED / "pooled_features.csv"
    if not feat_path.exists():
        # create a compact note only
        (OUT_DIR / "base_to_trajectory_regression_summary.md").write_text(
            "# Base Features vs Trajectory\n\n"
            "- `pooled_features.csv` not found in `plots/base_feature_prediction/`.\n"
            "- To enable this stage, save per-question features+labels from prediction script.\n",
            encoding="utf-8",
        )
        pd.DataFrame().to_csv(OUT_DIR / "base_to_trajectory_correlations.csv", index=False)
        print("Missing pooled_features.csv; wrote placeholder outputs.")
        return

    feat = pd.read_csv(feat_path)
    traj = pd.read_csv(by_q_path)
    # Focus on method/subset-level per-question mid trajectory outputs
    targ = traj[traj["layer_band"].isin(["mid", "core_mid"])].copy()
    merged = feat.merge(targ, on=["method", "question_idx", "subset"], how="inner")
    if merged.empty:
        pd.DataFrame().to_csv(OUT_DIR / "base_to_trajectory_correlations.csv", index=False)
        (OUT_DIR / "base_to_trajectory_regression_summary.md").write_text(
            "# Base Features vs Trajectory\n\n- No overlapping rows after merge.\n",
            encoding="utf-8",
        )
        return

    corr_rows = []
    targets = ["auc", "ck8", "slope_per_ckpt", "delta_ck8_minus_base"]
    for t in targets:
        for f in FEATURES:
            if f not in merged.columns:
                continue
            sub = merged[[f, t]].dropna()
            if len(sub) < 5:
                continue
            rho, p = spearmanr(sub[f], sub[t])
            corr_rows.append({"feature": f, "target": t, "spearman_rho": rho, "p_value": p, "n": len(sub)})
    corr_df = pd.DataFrame(corr_rows)
    corr_df.to_csv(OUT_DIR / "base_to_trajectory_correlations.csv", index=False)

    lines = ["# Base to Trajectory Regression Summary", ""]
    for t in targets:
        cols = [f for f in FEATURES if f in merged.columns]
        sub = merged[cols + [t]].dropna()
        if len(sub) < 10:
            lines.append(f"- {t}: skipped (n<{10})")
            continue
        X = sub[cols].values
        y = sub[t].values
        pipe = Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler()), ("lr", LinearRegression())])
        pipe.fit(X, y)
        r2 = pipe.score(X, y)
        coefs = pipe.named_steps["lr"].coef_
        top = sorted(zip(cols, coefs), key=lambda x: abs(x[1]), reverse=True)[:3]
        lines.append(f"- {t}: R^2={r2:.3f}; top(|coef|): " + ", ".join([f"{k}={v:.3f}" for k, v in top]))
    (OUT_DIR / "base_to_trajectory_regression_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("Saved outputs to:", OUT_DIR)


if __name__ == "__main__":
    main()
